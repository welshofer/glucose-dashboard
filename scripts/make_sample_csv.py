"""Write a synthetic LibreView-style CSV for trying the dashboard.

The readings are made up: a smooth daily curve with meal bumps and noise,
seeded so the file is the same every run. No real person's data is used.

    python3 scripts/make_sample_csv.py > sample-data/sample-libreview.csv
"""

import math
import random
import sys
from datetime import datetime, timedelta

DAYS = 30
STEP = timedelta(minutes=5)
START = datetime(2026, 1, 5)
MEALS = ((7.5, 45), (12.5, 40), (18.5, 55))  # (hour, mg/dL bump)


def reading(t: datetime, rng: random.Random, big_dinner: bool, night_low: bool) -> int:
    hour = t.hour + t.minute / 60
    value = 112 + 8 * math.sin((hour - 4) / 24 * 2 * math.pi)
    for meal_hour, bump in MEALS:
        dt = hour - meal_hour
        if meal_hour > 17 and big_dinner:
            bump *= 2.2
        if 0 <= dt < 3:
            value += bump * math.exp(-((dt - 0.9) ** 2) / 0.5)
    if night_low:
        value -= 52 * math.exp(-((hour - 3.0) ** 2) / 0.6)
    if t.weekday() >= 5:
        value += 6
    value += rng.gauss(0, 7)
    return max(45, min(320, round(value)))


def main() -> None:
    rng = random.Random(42)
    out = sys.stdout
    out.write("Glucose Data,Generated on,02-04-2026 9:00 AM UTC,Generated by,Sample Data\n")
    out.write(
        "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,"
        "Scan Glucose mg/dL,Non-numeric Rapid-Acting Insulin,Rapid-Acting Insulin (units),"
        "Non-numeric Food,Carbohydrates (grams),Carbohydrates (servings),"
        "Non-numeric Long-Acting Insulin,Long-Acting Insulin Value (units),Notes,"
        "Strip Glucose mg/dL,Ketone mmol/L,Meal Insulin (units),"
        "Correction Insulin (units),User Change Insulin (units)\n"
    )
    t = START
    end = START + timedelta(days=DAYS)
    while t < end:
        if t.hour == 0 and t.minute == 0:
            big_dinner = rng.random() < 0.25
            night_low = rng.random() < 0.15
        stamp = t.strftime("%m-%d-%Y %I:%M %p")
        value = reading(t, rng, big_dinner, night_low)
        out.write(f"FreeStyle Libre 3,SAMPLE-0000,{stamp},0,{value}" + "," * 14 + "\n")
        t += STEP


if __name__ == "__main__":
    main()
